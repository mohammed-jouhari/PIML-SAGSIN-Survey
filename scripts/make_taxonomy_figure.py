"""Generate figures/fig_taxonomy.tex (TikZ) from tools/screening_table.xlsx.

Rows = SAGSIN segment, columns = layer or function, cell = number of papers that embed an
identifiable physical law ("PIML primary"), with letters for how the physics enters.
Rerun after every update of the screening table:  python scripts/make_taxonomy_figure.py
"""
from pathlib import Path
import pandas as pd

HERE = Path(__file__).resolve().parent
df = pd.read_excel(HERE.parent / "data" / "screening_table.xlsx", sheet_name="Screening")
p = df[df["Role"] == "PIML primary"]

SEGS = ["Space", "Air", "Ground", "Sea surface", "Underwater", "Cross-segment"]
LAYS = [("PHY", "Physical\\\\layer"), ("Link", "Link\\\\layer"), ("Network", "Network\\\\layer"),
        ("Digital twin", "Digital\\\\twin"), ("Security", "Security"), ("Platform dynamics", "Platform\\\\dynamics")]
CODE = {"loss": "L", "architecture": "A", "residual": "R", "generative-conditioning": "G", "operator": "O",
        "world-model/RL-constraint": "W", "consistency-check": "C", "features": "F", "sim-pretraining": "S"}

def codes(sub):
    out = set()
    for m in sub["How physics enters"].astype(str):
        for part in m.split(","):
            c = CODE.get(part.strip())
            if c:
                out.add(c)
    return "".join(sorted(out))

W, H = 2.25, 0.95   # cell size in cm
lines = [r"% Auto-generated by tools/make_taxonomy_figure.py from the screening table. Do not edit by hand.",
         r"\begin{tikzpicture}[font=\footnotesize]"]
for j, (_, lab) in enumerate(LAYS):
    x = 2.6 + j * W + W / 2
    lines.append(rf"\node[align=center, font=\footnotesize\bfseries] at ({x:.2f},0.55) {{{lab}}};")
maxc = max(1, max(len(p[(p['Segment'] == s) & (p['Layer / function'] == l)]) for s in SEGS for l, _ in LAYS))
for i, s in enumerate(SEGS):
    y = -i * H
    lines.append(rf"\node[anchor=east, font=\footnotesize\bfseries] at (2.5,{y - H / 2 + 0.02:.2f}) {{{s}}};")
    for j, (l, _) in enumerate(LAYS):
        x0 = 2.6 + j * W
        sub = p[(p["Segment"] == s) & (p["Layer / function"] == l)]
        n = len(sub)
        if n == 0:
            lines.append(rf"\draw[gray!60, pattern=north east lines, pattern color=gray!35] ({x0:.2f},{y:.2f}) rectangle ({x0 + W - 0.08:.2f},{y - H + 0.08:.2f});")
            lines.append(rf"\node[text=gray!80!black, font=\scriptsize\itshape] at ({x0 + (W - 0.08) / 2:.2f},{y - (H - 0.08) / 2:.2f}) {{open}};")
        else:
            shade = int(15 + 70 * n / maxc)
            txt = "white" if shade > 55 else "black"
            lines.append(rf"\fill[blue!{shade}!white] ({x0:.2f},{y:.2f}) rectangle ({x0 + W - 0.08:.2f},{y - H + 0.08:.2f});")
            lines.append(rf"\node[text={txt}, font=\small\bfseries] at ({x0 + (W - 0.08) / 2:.2f},{y - 0.32:.2f}) {{{n}}};")
            lines.append(rf"\node[text={txt}, font=\scriptsize] at ({x0 + (W - 0.08) / 2:.2f},{y - 0.66:.2f}) {{{codes(sub)}}};")
yl = -len(SEGS) * H - 0.35
lines.append(rf"\node[anchor=north west, align=left, text width=15.8cm, font=\scriptsize] at (0.3,{yl + 0.2:.2f}) "
             r"{How physics enters: L = loss term, A = architecture or hard constraint, R = hybrid residual, "
             r"G = generative conditioning, W = world model or RL constraint, C = consistency check, F = physics features, "
             r"S = pretraining on physics simulations, O = neural operator.};")
lines.append(r"\end{tikzpicture}")
(HERE.parent / "figures" / "fig_taxonomy.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("cells written; PIML primary papers:", len(p))